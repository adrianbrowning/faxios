import { readFileSync } from "node:fs";
import { CLIENT_LABELS, CLIENTS, STAGE_LABELS, STAGES } from "./entries.ts";
import type { Client, Stage } from "./entries.ts";
import { runtimeResultsSchema, sizeResultsSchema } from "./results-schema.ts";
import type { Meta, RuntimeResults } from "./results-schema.ts";

const benchDir = new URL("../", import.meta.url);
const read = (path: string) => readFileSync(new URL(path, benchDir), "utf8");

const size = sizeResultsSchema.parse(JSON.parse(read("results/size.json")));
const runtime = runtimeResultsSchema.parse(JSON.parse(read("results/runtime.json")));

const kB = (bytes: number) => `${(bytes / 1000).toFixed(2)} kB`;
const row = (cells: ReadonlyArray<number | string>) => `| ${cells.join(" | ")} |`;
const header = (cells: ReadonlyArray<string>, align: ReadonlyArray<"l" | "r">) =>
  [ row(cells), row(align.map(a => (a === "r" ? "---:" : "---"))) ].join("\n");

function scenario(client: Client, stage: Stage) {
  const found = size.scenarios.find(s => s.client === client && s.stage === stage);
  if (!found) throw new Error(`results/size.json has no ${client} ${stage} bundle`);
  return found;
}

// Microseconds below 1ms, so wrapper-only numbers stay readable.
function duration(ms: number): string {
  return ms < 1 ? `${(ms * 1000).toFixed(1)} µs` : `${ms.toFixed(2)} ms`;
}

function environment(meta: Meta, what: string): string {
  const versions = Object.entries(meta.versions).map(([ name, version ]) => `${name} ${version}`)
    .join(", ");
  return [
    `- **${what}:** ${meta.date.slice(0, 10)} on ${meta.platform.cpu} (${meta.platform.cores} cores, ${meta.platform.memoryGiB} GiB),`
    + ` ${meta.platform.os} ${meta.platform.release} ${meta.platform.arch}, Node.js ${meta.runtime.version}.`,
    `  faxios packed from commit \`${meta.commit.slice(0, 12)}\`${meta.libDirty ? " with uncommitted library changes" : ""}. ${versions}.`,
  ].join("\n");
}

function runtimeTable(mode: RuntimeResults["results"][number]["mode"]): string {
  const results = runtime.results.filter(r => r.mode === mode);
  return [
    header([ "Scenario", "Client", "Median", "p95", "p99", "Ops/s (one in flight)", "Attempts per op", "Samples" ], [ "l", "l", "r", "r", "r", "r", "r", "r" ]),
    ...STAGES.flatMap(stage => results.filter(r => r.stage === stage).map(r => row([
      STAGE_LABELS[stage],
      r.secondary ? `${CLIENT_LABELS[r.client]} (default Node adapter, secondary)` : CLIENT_LABELS[r.client],
      duration(r.latencyMs.p50),
      duration(r.latencyMs.p95),
      duration(r.latencyMs.p99),
      Math.round(r.opsPerSecond).toLocaleString("en-US"),
      r.attemptsPerOp,
      r.samples.toLocaleString("en-US"),
    ]))),
  ].join("\n");
}

